// Function to get all unique amenities
export const getAllAmenities = () => {
  const amenitiesSet = new Set();
  cafeData.forEach((cafe) => {
    cafe.amenities.forEach((amenity) => amenitiesSet.add(amenity));
  });
  return Array.from(amenitiesSet).sort();
};

// Function to get all unique locations
export const getAllLocations = () => {
  return [...new Set(cafeData.map((cafe) => cafe.location))].sort();
};

// Function to filter cafes by location
export const filterByLocation = (location) => {
  if (!location) return cafeData;
  return cafeData.filter((cafe) =>
    cafe.location.toLowerCase().includes(location.toLowerCase())
  );
};

// Function to filter cafes by amenities
export const filterByAmenities = (selectedAmenities) => {
  if (!selectedAmenities || selectedAmenities.length === 0) return cafeData;
  return cafeData.filter((cafe) =>
    selectedAmenities.every((amenity) => cafe.amenities.includes(amenity))
  );
};

// Function to filter cafes by both location and amenities
export const filterCafes = (location, selectedAmenities) => {
  let filtered = cafeData;

  if (location) {
    filtered = filtered.filter((cafe) =>
      cafe.location.toLowerCase().includes(location.toLowerCase())
    );
  }

  if (selectedAmenities && selectedAmenities.length > 0) {
    filtered = filtered.filter((cafe) =>
      selectedAmenities.every((amenity) => cafe.amenities.includes(amenity))
    );
  }

  return filtered;
};

// Function to get cafe by ID
export const getCafeById = (id) => {
  return cafeData.find((cafe) => cafe.id === id);
};

// Function to update available seats (for owner functionality)
export const updateAvailableSeats = (cafeId, newSeatCount) => {
  const cafe = cafeData.find((c) => c.id === cafeId);
  if (cafe) {
    cafe.availableSeats = newSeatCount;
    return true;
  }
  return false;
};

export default cafeData;
